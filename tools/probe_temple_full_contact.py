def full_contact_reference(actor, reader, overlap, edges, metadata, view, neighbors,
                            *, available=True, height=74, bars=0):
    result = contact_reference(actor, reader, overlap, 25, sequence_available=available, mark=79)
    result.update(anchor=73, remainder=79, reason=71, distance=None)
    if result['events'] == [('eject',)]:
        geometry = ejection_reference(result['actor'], reader.cache[1] & 65535,
                                       reader.cache[3], reader.cache[4], edges, view, neighbors)
        result.update(actor=geometry['actor'], anchor=geometry['anchor'])
    elif result['events'] == [('resource', 50), ('distance',)]:
        measured = soft_distance_reference(result['actor'], reader, edges, metadata, view,
                                            neighbors, height=height, bars=bars)
        result.update(measured)
        if measured['distance'] < 25:
            updated = bytearray(result['actor'])
            delta = signed_word(measured['distance'] - 25)
            delta = -delta if actor_word(updated, 2) == -1 else delta
            put_actor(updated, 4, actor_word(updated, 4) + delta)
            result['actor'] = bytes(updated)
    elif result['events']:
        raise ValueError('Non-temple response outside the full contact fixture')
    return result


class NativeTempleFullContact(NativeTempleGateContact):
    RANGES = {segment: NativeTempleGateContact.RANGES.get(segment, ())
              + NativeTempleSoftDistance.RANGES.get(segment, ())
              for segment in NativeTempleGateContact.RANGES.keys() | NativeTempleSoftDistance.RANGES.keys()}
    RANGES[4] += ((0x6202, 0x62b0),)

    def dispatch(self, cpu, address, size, user):
        if address in (self.address(4, 0x5eae), self.address(4, 0x6202)):
            self.events.append(('distance' if address == self.address(4, 0x5eae) else 'eject',))
            NativeTempleSoftDistance.dispatch(self, cpu, address, size, user)
            return
        super().dispatch(cpu, address, size, user)


def run_probe(source):
    forks = Path(source) / 'resource_forks'
    executable = (forks / 'Prince of Persia 2.bin').read_bytes()
    prince = parse_resource_fork((forks / 'Prince.rsrc.bin').read_bytes())
    machine = NativeTempleFullContact(parse_resource_fork(executable))
    sequence_fixture = struct.pack('>I', SEQUENCE_HANDLE + 4) + prince['SEQS'][50]['data']
    machine.cpu.mem_write(SEQUENCE_HANDLE, sequence_fixture)
    counts, responses, digest = Counter(), Counter(), hashlib.sha256()

    def check(level, actor, edges, metadata, overlap, available, label, height=74):
        room = actor_word(actor, 22)
        left, right = struct.unpack_from('>2H', level, 0x2080 + (room - 1) * 8)
        neighbors = (left, 0, 0, right, 0, 0)
        machine.reset(level)
        machine.sequence_available = available
        machine.cpu.mem_write(machine.A5 - 0x5056, actor)
        machine.cpu.mem_write(machine.A5 - 0x50d2, bytes(range(62)))
        machine.cpu.mem_write(machine.A5 - 0x448e, bytes(range(160)))
        machine.cpu.mem_write(machine.A5 - 0x34b0, struct.pack('>6h', *COLD_CACHE))
        for offset, value in ((-0x4fc2, room), (-0x35fc, 73), (-0x3576, 71),
                              (-0x481c, 79), (-0x4f9e, 79), (-0x3564, edges[0]),
                              (-0x3566, edges[1]), (-0x3560, height), (-0x520e, metadata[0]),
                              (-0x520a, metadata[1]), (-0x36bc, 0)):
            machine.put_word(offset, value)
        for offset, value in zip(NEIGHBOR_SLOTS, neighbors):
            machine.put_word(offset, value)
        for offset, bank in zip((-0x355e, -0x354a), overlap):
            machine.cpu.mem_write(machine.A5 + offset, struct.pack('>10H', *bank))
        reader = ContactCellReader(level, room)
        expected = full_contact_reference(actor, reader, overlap, edges, metadata, room, neighbors,
                                          available=available, height=height)
        before = bytearray(machine.cpu.mem_read(machine.A5 - len(machine.data), len(machine.data)))
        machine.call(4, 0x60e4)
        before[len(machine.data) - 0x5056:len(machine.data) - 0x5056 + 62] = expected['actor']
        for offset, name in ((-0x35fc, 'anchor'), (-0x3576, 'reason'),
                             (-0x481c, 'remainder'), (-0x4f9e, 'mark')):
            struct.pack_into('>h', before, len(machine.data) + offset, expected[name])
        struct.pack_into('>6h', before, len(machine.data) - 0x34b0, *reader.cache)
        if reader.pointer_room is not None:
            r = reader.pointer_room
            struct.pack_into('>II', before, len(machine.data) - 0x4824,
                             machine.LEVEL + 0x780 + (r - 1) * 120,
                             machine.LEVEL + (r - 1) * 60)
        after = bytes(machine.cpu.mem_read(machine.A5 - len(machine.data), len(machine.data)))
        if (after != before or machine.services or machine.reads != reader.requests
                or machine.events != expected['events'] or machine.level_bytes(len(level)) != level
                or bytes(machine.cpu.mem_read(SEQUENCE_HANDLE, len(sequence_fixture))) != sequence_fixture):
            raise AssertionError(dict(label=label, actor=actor.hex(), edges=edges, metadata=metadata,
                actual_events=machine.events, expected=expected, reads=machine.reads,
                expected_reads=reader.requests, changed=[(hex(i - len(machine.data)), a, b)
                for i, (a, b) in enumerate(zip(before, after)) if a != b]))
        counts[label] += 1
        responses['eject' if ('eject',) in expected['events'] else
                  'soft' if ('distance',) in expected['events'] else 'none'] += 1
        digest.update(expected['actor'] + struct.pack('>4h6h', expected['mark'], expected['anchor'],
                      expected['reason'], expected['remainder'], *reader.cache))
        digest.update(json.dumps((expected['events'], machine.reads)).encode('ascii'))

    gates = 0
    for number in range(10, 14):
        original = prince['LEVL'][1999 + number]['data']
        for room, cell in product(range(1, 33), range(30)):
            if struct.unpack_from('>H', original, (room - 1) * 60 + cell * 2)[0] != 4:
                continue
            gates += 1
            row, col = divmod(cell, 10)
            for facing, relative, phase, source, delta, metadata, available in product(
                    (-1, 0), (-1, 0, 1), (0, 1, 96, 184, 0x8100), (9, 50, 118),
                    (-25, 25, 65), ((0, 0), (8, 0), (8, 0x7f)), (True, False)):
                level = bytearray(original)
                struct.pack_into('>H', level, 0x780 + (room - 1) * 120 + cell * 4, phase)
                actor = bytearray(actor_fixture(room, row, col + relative, facing, 0))
                x = 229 + col * 51 + delta
                for offset, value in ((4, x), (10, 1), (26, 0), (28, -1), (30, 3),
                                      (40, source), (42, 20), (46, 94)):
                    put_actor(actor, offset, value)
                check(bytes(level), bytes(actor), (x - 15, x + 15), metadata,
                      ((255,) * 10,) * 2, available, 'original_gate_anchors')
    original = prince['LEVL'][2009]['data']
    for facing, height, (phase, source, alive, armed, pose, bits), available in product(
            (-1, 0), (34, 74),
            ((1, 9, -1, 0, 1, (255, 255)), (1, 9, -1, 0, 1, (511, 511)),
             (1, 9, -1, 0, 1, (511, 255)), (1, 118, -1, 0, 1, (255, 255)),
             (1, 9, 0, 0, 1, (255, 255)), (1, 9, -1, 1, 1, (255, 255)),
             (1, 9, -1, 0, 109, (255, 255)), (0, 50, -1, 0, 1, (255, 255)),
             (184, 9, -1, 0, 1, (255, 255)), (0x8100, 9, -1, 0, 1, (255, 255))),
            (True, False)):
        level = bytearray(original)
        for cell in range(30):
            struct.pack_into('>H', level, cell * 2, 1)
        struct.pack_into('>H', level, 14 * 2, 4)
        struct.pack_into('>H', level, 0x780 + 14 * 4, phase)
        struct.pack_into('>H', level, (13 if facing == -1 else 15) * 2, 0)
        actor = bytearray(actor_fixture(1, 1, 4, facing, 0))
        for offset, value in ((4, 460), (10, pose), (26, armed), (28, alive), (30, 3),
                              (40, source), (42, 20), (46, 20 + height)):
            put_actor(actor, offset, value)
        check(bytes(level), bytes(actor), (445, 475), (8, 0),
              tuple((v,) * 10 for v in bits), available, 'caller_controls', height)
    return dict(gates=gates, comparisons=dict(counts), responses=dict(responses), mismatches=0,
                executable_sha256=hashlib.sha256(executable).hexdigest(),
                outputs_sha256=digest.hexdigest(), supplied=['SEQS50 resource lookup, success/failure'],
                scope=__doc__)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    report = run_probe(args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, indent=2))
