"""Compose original temple contact with real distance selection and ejection.

Executes4:60e4,4:5eae,4:6202, JumpSeq50 and their real cells/admission/
geometry/arithmetic. Only SEQS50 Resource Manager lookup (success/failure)
is supplied. Body/overlap/frame/room slots are fixtures, not generated by
Collide/ShapeBounds/InitRoom. No AnimChar, damage, outer FrameAdv or gameplay.
"""

